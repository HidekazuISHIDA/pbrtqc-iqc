"""Where the data are read from and where results are written.

Two profiles:
  demo  synthetic raw exports generated by scripts/00_make_synthetic_raw.py (no patient data); everything under work_demo/
  real  the laboratory's own exports; their location is set in pbrtqc.local.json (never committed); results under work/

Selection: environment variable PBRTQC_PROFILE, else "profile" in pbrtqc.local.json, else "demo".
pbrtqc.local.json (real data, created by notebooks/00_setup.ipynb or by hand):
  {"profile": "real",
   "lis_raw_dir": "/path/to/lis_2023_2025",          folder with the LIS result exports (*.xlsx or *.csv)
   "qc_raw_file": "/path/to/QC2023_2025.xlsx",       the IQC export
   "reference_tables": "/path/to/reference/tables"}  optional: tables to compare with (notebooks/06_verify.ipynb)
Raw files are only read, never written. Derived files (pseudonymised cache, result tables) go to the work folder.
"""
from __future__ import annotations
import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOCAL = ROOT / "pbrtqc.local.json"


def _local() -> dict:
    try:
        return json.loads(LOCAL.read_text(encoding="utf-8"))
    except FileNotFoundError:
        return {}


LOCAL_CFG = _local()
PROFILE = os.environ.get("PBRTQC_PROFILE") or LOCAL_CFG.get("profile", "demo")
if PROFILE not in ("demo", "real"):
    raise ValueError(f"PBRTQC_PROFILE must be 'demo' or 'real', not {PROFILE!r}")

if PROFILE == "demo":
    WORK = ROOT / "work_demo"
    LIS_RAW = WORK / "raw" / "lis"
    QC_RAW = WORK / "raw" / "qc" / "qc_2023_2025.csv"
    REFERENCE = ROOT / "reference" / "demo_tables"
else:
    WORK = ROOT / "work"
    LIS_RAW = Path(LOCAL_CFG.get("lis_raw_dir", ROOT / "data" / "raw" / "lis_2023_2025")).expanduser()
    QC_RAW = Path(LOCAL_CFG.get("qc_raw_file", ROOT / "data" / "qc" / "QC2023_2025.xlsx")).expanduser()
    REFERENCE = Path(LOCAL_CFG["reference_tables"]).expanduser() if LOCAL_CFG.get("reference_tables") else None

PROCESSED = WORK / "processed"      # pseudonymised caches (patient-level, never shared)
TABLES = WORK / "tables"            # aggregate result tables
MONITOR = WORK / "monitor"          # data for the monitoring screen
for _p in (PROCESSED, TABLES, MONITOR):
    _p.mkdir(parents=True, exist_ok=True)


def describe() -> str:
    return (f"profile={PROFILE}\n  LIS raw : {LIS_RAW}\n  QC raw  : {QC_RAW}\n  work    : {WORK}\n"
            f"  reference tables: {REFERENCE}")
